"""Write brand/handoff/: drop-in files for the Shopify theme (v5).
    python3 handoff.py <brand-dir>
  logo.liquid        replaces theme/snippets/logo.liquid (same params and classes as the theme's v3 snippet, v5 paths)
  favicon-head.liquid replaces the favicon <link>s in theme/layout/theme.liquid and password.liquid
  favicon-cart.js    replaces the favicon block in KK.updateCartCount(count) (theme/assets/global.js)"""
import os, re, sys
B = sys.argv[1]
H = os.path.join(B, 'handoff'); os.makedirs(H, exist_ok=True)

def parts(name):
    s = open(os.path.join(B, 'svg', name)).read()
    vb = re.search(r'viewBox="([^"]+)"', s).group(1)
    letters = re.search(r'<path fill="currentColor" d="([^"]+)"/>', s).group(1)
    tent = re.search(r'<path class="kk-tent" fill="#C83812" d="([^"]+)"/>', s).group(1)
    return vb, letters, tent

def svg_tag(mod, vb, letters, tent):
    return (f'<svg class="logo-svg logo-svg--{mod}{{% if class %}} {{{{ class }}}}{{% endif %}}" viewBox="{vb}" role="img" '
            f'aria-label="{{{{ title | default: shop.name | escape }}}}" focusable="false"><path fill="currentColor" d="{letters}"/>'
            f'<path class="logo-svg__roof" fill="#C83812" style="fill:var(--logo-roof,var(--c-klaproos))" d="{tent}"/></svg>')

full = parts('logo-inline.svg'); klein = parts('logo-klein-inline.svg')
logo = f'''{{%- comment -%}}
  Klapklaar wordmark, inline (brand v5: brand/svg/logo-inline.svg and brand/svg/logo-klein-inline.svg, letters + tent as
  two paths). Generated by brand/tools/handoff.py - do not edit the paths by hand.
  Letters follow currentColor; the tent uses --logo-roof (Klaproos on light, Polder on Zakelijk pages, Zon on Polder/Inkt,
  or currentColor when settings.logo_roof = mono). Below 750 px the header shows logo-klein (brand.md 3.3: logo.svg needs
  at least 149 px), so both drawings are rendered and CSS picks one.
  Params: class (string), title (string, defaults to shop name), image (bool: honour settings.logo upload),
          variant: 'auto' (both, CSS switch), 'full' or 'klein'
{{%- endcomment -%}}
{{%- assign logo_variant = variant | default: 'full' -%}}
{{%- if image and settings.logo != blank -%}}
  {{%- capture logo_sizes -%}}(min-width: 990px) {{{{ settings.logo_width }}}}px, {{{{ settings.logo_width_mobile }}}}px{{%- endcapture -%}}
  {{{{- settings.logo | image_url: width: 600 | image_tag: class: 'logo-img', alt: shop.name, widths: '150, 225, 300, 450, 600', sizes: logo_sizes, loading: 'eager' -}}}}
{{%- else -%}}
  {{%- if logo_variant == 'full' or logo_variant == 'auto' -%}}
{svg_tag('full', *full)}
  {{%- endif -%}}
  {{%- if logo_variant == 'klein' or logo_variant == 'auto' -%}}
{svg_tag('klein', *klein)}
  {{%- endif -%}}
{{%- endif -%}}
'''
open(os.path.join(H, 'logo.liquid'), 'w').write(logo)

head = '''{%- comment -%}
  Klapklaar favicons (brand v5, technisch.md 6.5). PNG only: no type="image/svg+xml" link, so the 16 px drawing is used at 16 px.
  Theme assets: favicon-16.png, favicon-32.png, favicon-192.png, apple-touch-icon-180.png, favicon-cart-16.png, favicon-cart-32.png.
  Replaces the else-branch of the favicon block in layout/theme.liquid (and the favicon link in layout/password.liquid).
{%- endcomment -%}
{%- liquid
  assign fav = ''
  if cart.item_count > 0
    assign fav = '-cart'
  endif
-%}
<link rel="icon" type="image/png" sizes="16x16" href="{{ 'favicon' | append: fav | append: '-16.png' | asset_url }}" data-favicon="16">
<link rel="icon" type="image/png" sizes="32x32" href="{{ 'favicon' | append: fav | append: '-32.png' | asset_url }}" data-favicon="32">
<link rel="icon" type="image/png" sizes="192x192" href="{{ 'favicon-192.png' | asset_url }}">
<link rel="apple-touch-icon" sizes="180x180" href="{{ 'apple-touch-icon-180.png' | asset_url }}">
<script>
  window.KK = window.KK || {};
  KK.favicons = {
    16: { base: {{ 'favicon-16.png' | asset_url | json }}, cart: {{ 'favicon-cart-16.png' | asset_url | json }} },
    32: { base: {{ 'favicon-32.png' | asset_url | json }}, cart: {{ 'favicon-cart-32.png' | asset_url | json }} }
  };
</script>
'''
open(os.path.join(H, 'favicon-head.liquid'), 'w').write(head)

js = '''// Klapklaar favicon cart state (brand v5, technisch.md 6.5).
// Put this inside KK.updateCartCount(count) in theme/assets/global.js, in place of the block that reads
// link[data-favicon] and KK.faviconCart. KK.favicons comes from handoff/favicon-head.liquid.
document.querySelectorAll('link[data-favicon]').forEach((link) => {
  const f = KK.favicons && KK.favicons[link.dataset.favicon];
  if (f) link.href = count > 0 ? f.cart : f.base;
});
'''
open(os.path.join(H, 'favicon-cart.js'), 'w').write(js)
print('handoff ok', len(logo))
