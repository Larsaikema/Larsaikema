"""Write brand/handoff/: drop-in files for the Shopify theme (v7.1).
    python3 handoff.py <brand-dir>
  logo.liquid        replaces theme/snippets/logo.liquid (variants full / klein / auto / zakelijk, v7.1 paths)
  logo-css.txt       the CSS lines for theme/assets/base.css and theme/snippets/css-variables.liquid (one-colour tent swap)
  favicon-head.liquid replaces the favicon <link>s in theme/layout/theme.liquid and password.liquid
  favicon-cart.js    replaces the favicon block in KK.updateCartCount(count) (theme/assets/global.js)"""
import os, re, sys
B = sys.argv[1]
H = os.path.join(B, 'handoff'); os.makedirs(H, exist_ok=True)

def paths_of(name):
    s = open(os.path.join(B, name)).read()
    vb = re.search(r'viewBox="([^"]+)"', s).group(1)
    return vb, re.findall(r'<path[^>]*\sd="([^"]+)"', s)

def parts(name):
    s = open(os.path.join(B, 'svg', name)).read()
    vb = re.search(r'viewBox="([^"]+)"', s).group(1)
    letters = re.search(r'<path fill="currentColor" d="([^"]+)"/>', s).group(1)
    tent = re.search(r'<path class="kk-tent" fill="#E66414" d="([^"]+)"/>', s).group(1)
    return vb, letters, tent

ROOF = 'class="logo-svg__roof" fill="#E66414" style="fill:var(--logo-roof,var(--c-lampion))"'
def svg_tag(mod, vb, letters, tent, mono_tent=None):
    # full: slender tent (two colours) plus the heavy tent at opacity 0; when the scheme's tent is one colour
    # (--logo-tent-mono: 1) CSS fades the slender one out and the heavy one in. klein: the heavy tent only.
    s = (f'<svg class="logo-svg logo-svg--{mod}{{% if class %}} {{{{ class }}}}{{% endif %}}" viewBox="{vb}" role="img" '
         f'aria-label="{{{{ title | default: shop.name | escape }}}}" focusable="false"><path fill="currentColor" d="{letters}"/>'
         f'<path {ROOF} d="{tent}"/>')
    if mono_tent: s += f'<path class="logo-svg__roof-mono" fill="currentColor" opacity="0" d="{mono_tent}"/>'
    return s + '</svg>'

full = parts('logo-inline.svg'); klein = parts('logo-klein-inline.svg')
vb_m, (letters_m, heavy_full) = paths_of('svg/logo-mono.svg')
assert vb_m == full[0] and letters_m == full[1], 'logo-mono.svg must share letters and viewBox with logo-inline.svg'
vb_z, zp = paths_of('svg/logo-zakelijk.svg')       # [letters + heavy tent, ZAKELIJK tag (evenodd)]
zak = (f'<svg class="logo-svg logo-svg--zakelijk{{% if class %}} {{{{ class }}}}{{% endif %}}" viewBox="{vb_z}" role="img" '
       f'aria-label="{{{{ title | default: shop.name | escape }}}} {{{{ \'general.zakelijk\' | t }}}}" focusable="false">'
       f'<path fill="currentColor" d="{zp[0]}"/><path fill="currentColor" fill-rule="evenodd" d="{zp[1]}"/></svg>')
logo = f"""{{%- comment -%}}
  Klapklaar wordmark v7.1, inline. Generated by brand/tools/handoff.py from svg/logo-inline.svg, svg/logo-mono.svg,
  svg/logo-klein-inline.svg and svg/logo-zakelijk.svg (KLAPKLAAR in drawn capitals, the second A of KLAAR is a party tent):
  do not edit the paths. Letters are currentColor and follow the colour scheme's text colour; the tent (.logo-svg__roof)
  is filled with the scheme's 'Tent in het logo' (Lampion on Zand/Wit/Inkt; Inkt, one colour, on Linnen, Lampion, Zakelijk).
  Two tent drawings (brand.md 3.4): the slender tent-A only in two colours from 160 px; the heavy tent-A below 160 px
  (logo-klein) and wherever the tent is one colour. 'full' carries both: when the scheme sets --logo-tent-mono: 1
  (tent colour = text colour, or 'Tent overal in de kleur van de letters'), base.css shows .logo-svg__roof-mono instead.
  Below 750 px the header shows logo-klein (logo.svg from 160 px, logo-klein 96-159 px); both drawings are rendered and
  CSS picks one. variant 'zakelijk' = the one-colour wordmark with the ZAKELIJK label (brand.md 3.3/3.8).
  Params: class (string), title (string, defaults to shop name), image (bool: honour settings.logo upload),
          variant: 'auto' (both, CSS switch), 'full', 'klein' or 'zakelijk'
{{%- endcomment -%}}
{{%- assign logo_variant = variant | default: 'full' -%}}
{{%- if image and settings.logo != blank -%}}
  {{%- capture logo_sizes -%}}(min-width: 750px) {{{{ settings.logo_width }}}}px, {{{{ settings.logo_width_mobile }}}}px{{%- endcapture -%}}
  {{{{- settings.logo | image_url: width: 600 | image_tag: class: 'logo-img', alt: shop.name, widths: '150, 225, 300, 450, 600', sizes: logo_sizes, loading: 'eager' -}}}}
{{%- else -%}}
  {{%- if logo_variant == 'full' or logo_variant == 'auto' -%}}
{svg_tag('full', *full, mono_tent=heavy_full)}
  {{%- endif -%}}
  {{%- if logo_variant == 'klein' or logo_variant == 'auto' -%}}
{svg_tag('klein', *klein)}
  {{%- endif -%}}
  {{%- if logo_variant == 'zakelijk' -%}}
{zak}
  {{%- endif -%}}
{{%- endif -%}}
"""
open(os.path.join(H, 'logo.liquid'), 'w').write(logo)

css = """/* theme/assets/base.css (brand v7.1: one-colour tent = the heavy tent-A) */
.kk-tent,.logo-svg__roof{fill:var(--logo-tent,var(--c-brand))!important}
.logo-svg--full .logo-svg__roof{opacity:calc(1 - var(--logo-tent-mono,0))}   /* klein already carries the heavy tent */
.logo-svg__roof-mono{opacity:var(--logo-tent-mono,0)}
.is-zakelijk :is(.header-wrap,.menu-drawer,.footer){--logo-tent:var(--logo-tent-zakelijk);--logo-tent-mono:var(--logo-tent-mono-zakelijk)}

{%- comment -%} theme/snippets/css-variables.liquid, :root {%- endcomment -%}
--logo-tent-mono-zakelijk: {% if settings.logo_zakelijk_mono or settings.logo_tent_mono %}1{% else %}var(--logo-tent-mono){% endif %};

{%- comment -%} theme/snippets/css-variables.liquid, per colour scheme, next to --logo-tent {%- endcomment -%}
{%- assign logo_tent_hex = scheme.settings.logo_tent | color_to_hex -%}
{%- assign logo_fg_hex = scheme.settings.foreground | color_to_hex -%}
--logo-tent-mono: {% if settings.logo_tent_mono or logo_tent_hex == logo_fg_hex %}1{% else %}0{% endif %};
"""
open(os.path.join(H, 'logo-css.txt'), 'w').write(css)

head = '''{%- comment -%}
  Klapklaar favicons (brand v7.1, technisch.md 6.5: the square icon, drawn on the 16 and 32 grid). PNG only: no type="image/svg+xml" link, so the 16 px drawing is used at 16 px.
  Theme assets: favicon-16.png, favicon-32.png, favicon-192.png, apple-touch-icon-180.png, favicon-cart-16.png, favicon-cart-32.png.
  Replaces the else-branch of the favicon block in layout/theme.liquid (and the favicon link in layout/password.liquid).
{%- endcomment -%}
{%- liquid
  assign fav = ''
  if cart.item_count > 0
    assign fav = '-cart'
  endif
-%}
<link rel="icon" type="image/png" sizes="16x16" href="{{ 'favicon' | append: fav | append: '-16.png' | asset_url }}" data-favicon="16">
<link rel="icon" type="image/png" sizes="32x32" href="{{ 'favicon' | append: fav | append: '-32.png' | asset_url }}" data-favicon="32">
<link rel="icon" type="image/png" sizes="192x192" href="{{ 'favicon-192.png' | asset_url }}">
<link rel="apple-touch-icon" sizes="180x180" href="{{ 'apple-touch-icon-180.png' | asset_url }}">
<script>
  window.KK = window.KK || {};
  KK.favicons = {
    16: { base: {{ 'favicon-16.png' | asset_url | json }}, cart: {{ 'favicon-cart-16.png' | asset_url | json }} },
    32: { base: {{ 'favicon-32.png' | asset_url | json }}, cart: {{ 'favicon-cart-32.png' | asset_url | json }} }
  };
</script>
'''
open(os.path.join(H, 'favicon-head.liquid'), 'w').write(head)

js = '''// Klapklaar favicon cart state (brand v7.1, technisch.md 6.5).
// Put this inside KK.updateCartCount(count) in theme/assets/global.js, in place of the block that reads
// link[data-favicon] and KK.faviconCart. KK.favicons comes from handoff/favicon-head.liquid.
document.querySelectorAll('link[data-favicon]').forEach((link) => {
  const f = KK.favicons && KK.favicons[link.dataset.favicon];
  if (f) link.href = count > 0 ? f.cart : f.base;
});
'''
open(os.path.join(H, 'favicon-cart.js'), 'w').write(js)
print('handoff ok', len(logo))
