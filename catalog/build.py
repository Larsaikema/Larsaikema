def read_stock(path: Path = STOCK_FILE):
    """{sku: qty} from the owner's stock.csv (comma or semicolon separated; rows with an empty Voorraad are skipped)."""
    if not path.exists():
        return {}, []
    text = path.read_text(encoding='utf-8-sig')
    dialect = csv.Sniffer().sniff(text.splitlines()[0], delimiters=',;') if text.strip() else csv.excel
    out, bad = {}, []
    for row in csv.DictReader(io.StringIO(text), dialect=dialect):
        sku = (row.get('SKU') or '').strip()
        raw = (row.get('Voorraad') or '').strip()
        if not sku or raw == '':
            continue
        try:
            qty = int(raw)
        except ValueError:
            bad.append(f'{sku}: Voorraad {raw!r} is no whole number')
            continue
        if qty < 0:
            bad.append(f'{sku}: Voorraad {qty} < 0')
            continue
        out[sku] = qty
    return out, bad


def apply_stock(b, products):
    """Real stock from catalog/stock.csv onto tracked variants (inventory_quantity). Untouched variants keep 0 + continue."""
    stock, bad = read_stock()
    b.warnings.extend(f'stock.csv: {x}' for x in bad)
    by_sku = {v['sku']: (p, v) for p in products for v in p['variants']}
    applied = 0
    for sku, qty in stock.items():
        hit = by_sku.get(sku)
        if not hit:
            b.warnings.append(f'stock.csv: unknown SKU {sku}')
            continue
        p, v = hit
        if v.get('inventory_management') != 'shopify':
            b.warnings.append(f'stock.csv: {sku} is not tracked (made to order / bundle), Voorraad ignored')
            continue
        v['inventory_quantity'] = qty
        v['stock_counted'] = True   # a counted 0 stays 0 in the preview fixture (no demo stock on top of real stock)
        applied += 1
    if applied:
        b.fix('stock.csv', f'inventory_quantity from the owner stock file on {applied} variant(s)', 'catalog/stock.csv (owner input)')
    return applied


def write_stock_template(products, path: Path = STOCK_FILE):
    """Add a row per variant of the fast movers to stock.csv; filled Voorraad values and extra rows the owner added are kept."""
    keep, order = {}, []
    if path.exists():
        text = path.read_text(encoding='utf-8-sig')
        dialect = csv.Sniffer().sniff(text.splitlines()[0], delimiters=',;') if text.strip() else csv.excel
        for row in csv.DictReader(io.StringIO(text), dialect=dialect):
            sku = (row.get('SKU') or '').strip()
            if sku:
                keep[sku] = {c: (row.get(c) or '').strip() for c in STOCK_COLUMNS}
                order.append(sku)
    P = {p['handle']: p for p in products}
    for h in STOCK_FAST_MOVERS:
        p = P.get(h)
        if not p:
            continue
        for v in p['variants']:
            if v.get('inventory_management') != 'shopify' or v['sku'] in keep:
                continue
            title = ' / '.join(str(v[f'option{i}']) for i in (1, 2, 3) if v.get(f'option{i}')) or 'Standaard'
            keep[v['sku']] = {'SKU': v['sku'], 'Product': p['title'], 'Variant': title, 'Voorraad': ''}
            order.append(v['sku'])
    buf = io.StringIO(newline='')
    w = csv.DictWriter(buf, fieldnames=STOCK_COLUMNS, lineterminator='\n')
    w.writeheader()
    for sku in order:
        w.writerow(keep[sku])
    path.write_text(buf.getvalue(), encoding='utf-8')
    return len(order)


def write_redirects(path: Path, redirects, products):
    """Shopify URL redirect import (columns 'Redirect from', 'Redirect to'); only targets that exist, never a live handle."""
    live = {p['handle'] for p in products}
    rows = []
    for r in redirects or []:
        src, dst = r['from'], r['to']
        if src.startswith('/products/') and src.split('/')[-1] in live:
            raise SystemExit(f'redirect from a live product handle: {src}')
        if dst.startswith('/products/') and dst.split('/')[-1] not in live:
            raise SystemExit(f'redirect to a missing product: {dst}')
        rows.append({'Redirect from': src, 'Redirect to': dst})
    buf = io.StringIO(newline='')
    w = csv.DictWriter(buf, fieldnames=['Redirect from', 'Redirect to'], lineterminator='\n')
    w.writeheader()
    for r in rows:
        w.writerow(r)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(buf.getvalue(), encoding='utf-8')
    return len(rows)


