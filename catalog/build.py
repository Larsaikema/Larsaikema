    def derive(self, products):
        """Catalog round 2026-10-18: fields derived from the merged products (CONTRACT.md).
          * custom.gebruik: readable labels from the gebruik:* tags (the storefront filter shows these, never a raw tag);
          * custom.onderdelen (M2): every product whose custom.past_op lists this product (parts and accessories that fit it), bundles
            and gift cards left out, in catalog order;
          * the 'Los of in het pakket' table (data-kk="set-vs-los") of every bundle, rebuilt from the bundle data so a price change in
            the skeleton never leaves a stale amount in the copy."""
        P = self.by_handle
        for p in products:
            g = [GEBRUIK_LABELS[t] for t in p['tags'] if t in GEBRUIK_LABELS]
            p['metafields']['gebruik'] = g or None
        rev = {}
        for p in products:
            if 'set' in p['tags'] or p.get('gift_card'):
                continue
            for h in p['metafields'].get('past_op') or []:
                rev.setdefault(h, []).append(p['handle'])
        n = 0
        for p in products:
            parts = [h for h in rev.get(p['handle'], []) if h != p['handle']]
            p['metafields']['onderdelen'] = parts or None
            n += bool(parts)
        self.fix('*', f'custom.onderdelen on {n} products from the reverse of custom.past_op', 'M2: parts list on the main PDP (CONTRACT)')
        rows = 0
        for p in products:
            if not p.get('bundle') or 'data-kk="set-vs-los"' not in p['body_html']:
                continue
            p['body_html'] = SET_VS_LOS.sub(lambda m: set_vs_los_table(p), p['body_html'], count=1)
            rows += 1
        if rows:
            self.fix('*', f'set-vs-los table rebuilt from bundle data on {rows} bundles', 'prices in copy follow the skeleton (catalog round 2026-10-18)')
        for h in WALL_SETS:
            p = P.get(h)
            if p and 'data-kk="set-vs-los"' in p['body_html']:
                p['body_html'] = SET_VS_LOS.sub(lambda m: wall_set_table(p, P), p['body_html'], count=1)
                self.fix(h, 'set-vs-los table rebuilt from the loose wall prices', 'catalog round 3: wall prices re-based; the copy never keeps a stale amount')

    def export_images(self, products):
        """Which images go to Shopify, and which one each variant shows. Only real renders are exported (never a draft card or
        a missing file). A variant gets a Variant Image only when that image shows the variant as it is:
          1. its own image (skeleton variant_images), when that is a real render;
          2. else, for a variant with a Kleur, another real image of the product in exactly that Kleur;
          3. else, for a bundle variant, the real image of one of its components in that Kleur (added to the bundle's images,
             the alt says it is a part of the pakket);
          4. else, for a product whose images do not vary per option (no variant_image_by) and a variant without a Kleur,
             the product's first real image;
          5. otherwise none: Variant Image stays empty and the product images carry the page. A Zwart render (with Zwart alt
             text) is never exported as the image of a Bordeaux variant (merchandising review)."""
        st = self.image_stats = {'real': 0, 'draft': 0, 'missing': 0, 'products_without_image': [], 'variants_own': 0,
                                 'variants_same_kleur': 0, 'variants_component': 0, 'variants_hero': 0, 'variants_no_image': 0,
                                 'variants_no_image_by_product': {}}
        for p in products:
            for img in p['images']:
                f = img['file']
                img['draft'] = is_draft(f)
                img['exported'] = (IMAGES / f).exists() and not img['draft']
                st['real' if img['exported'] else ('draft' if img['draft'] else 'missing')] += 1
        sku_variant = {v['sku']: (p, v) for p in products for v in p['variants']}

        def kleur_of(p, v):
            names = [o['name'] for o in p['options']]
            return v.get(f'option{names.index("Kleur") + 1}') if 'Kleur' in names else None

        def pick(p, v, allow_components):
            real = [i for i in p['images'] if i['exported']]
            own = v.get('image')
            if own and any(i['file'] == own for i in real):
                return own, 'own'
            k = kleur_of(p, v)
            if k:
                same = [i['file'] for i in real if i.get('kleur') == k]
                if same:
                    return same[0], 'same_kleur'
                if allow_components:
                    # only the component the bundle's Kleur refers to: its product offers every Kleur of the bundle (the rok in a
                    # statafel + rok pakket, not the statafel whose blad colour happens to have the same name)
                    bk = set(next((o['values'] for o in p['options'] if o['name'] == 'Kleur'), []))
                    for s in v['metafields'].get('componenten') or []:
                        cp, cv = sku_variant.get(s, (None, None))
                        if not cp or not bk <= set(next((o['values'] for o in cp['options'] if o['name'] == 'Kleur'), [])):
                            continue
                        ci = next((i for i in cp['images'] if i['file'] == cv.get('export_image') and i['exported'] and i.get('kleur') == k), None)
                        if ci:
                            if not any(i['file'] == ci['file'] for i in p['images']):
                                p['images'].append({**copy.deepcopy(ci), 'role': 'component', 'priority': max(3, ci.get('priority', 3)),
                                                    'alt': f"{ci['alt']} (onderdeel van dit pakket)", 'component_of': cp['handle']})
                            return ci['file'], 'component'
                return None, 'no_image'
            if not p.get('variant_image_by') and real:
                return real[0]['file'], 'hero'
            return None, 'no_image'

        # components first, so a bundle can fall back on the export image of its component
        for p in sorted(products, key=lambda x: 1 if x.get('bundle') else 0):
            for v in p['variants']:
                f, how = pick(p, v, bool(p.get('bundle')))
                v['export_image'] = f
                st['variants_' + how] += 1
                if how == 'no_image':
                    st['variants_no_image_by_product'][p['handle']] = st['variants_no_image_by_product'].get(p['handle'], 0) + 1
        for p in products:
            if not any(i['exported'] for i in p['images']):
                st['products_without_image'].append(p['handle'])

    def merge_product(self, sp, part):
        p = copy.deepcopy(sp)
        mf = p['metafields']
        p['body_html'] = part.get('body_html') or ''
        seo = part.get('seo') or {}
        p['seo'] = {'title': seo.get('title'), 'description': seo.get('description')}
        for k in ('kenmerk_kort', 'usps', 'specificaties', 'faq', 'included', 'excluded', 'drukopties',
                  'configurator', 'maatwerk'):
            if k in part and part[k] is not None:
                mf[k] = part[k]
        for k in list(mf):
            if k not in PRODUCT_MF_TYPES:
                raise SystemExit(f'{p["handle"]}: metafield {k} is not in the contract')
        alts = part.get('image_alts') or {}
        for img in p['images']:
            alt = (alts.get(img['file']) or '').strip()
            if not alt:
                hint = img.get('alt_hint')
                alt = f"{p['title']}{', ' + hint if hint else ''}"
                self.warnings.append(f"{p['handle']}: no alt text for {img['file']} in the copy part, used fallback")
            img['alt'] = alt
        # what the copy says the owner/supplier must confirm (not for the storefront)
        # catalog round 3 (M16): the opbouw- en veiligheidshandleiding of the product family (not a metafield: catalog/tools/productblad.mjs
        # --handleidingen renders it as opbouwhandleiding-<handle>.pdf, which fix 6b then attaches to custom.downloads)
        if part.get('handleiding'):
            p['handleiding'] = part['handleiding']
        claims = list(part.get('claims') or [])
        claims += [c for c in html_claims(p['body_html']) if c not in claims]
        p['claims'] = claims
        p['copy_group'] = self.part_group.get(p['handle'], p.get('copy_group'))
        # remove skeleton-only working fields from the merged record
        for k in ('copy_brief', 'seo_keywords', 'price_range_eur'):
            p.pop(k, None)
        # variants: native per-variant metafields container
        for v in p['variants']:
            v.setdefault('metafields', {})
        return p

    def apply_fixes(self, products):
        P = self.by_handle
        # 1. CONTRACT: no print lead time in custom.levertijd (drukopties.levertijd carries it)
        for p in products:
            mf = p['metafields']
            lev = mf.get('levertijd')
            if lev and 'drukproef' in lev:
                new = re.sub(r'\s*\((?:bij\s+)?bedrukt:[^)]*\)', '', lev).strip()
                if 'drukproef' in new or not mf.get('bedrukbaar'):
                    new = None
                mf['levertijd'] = new
                self.fix(p['handle'], f'custom.levertijd {lev!r} → {new!r}',
                         'CONTRACT: print lead time lives in drukopties.levertijd, not in levertijd (G5 note)')
        # 2. bedrukbaar without a print variant
        for h, why in NOT_PRINTABLE.items():
            p = P.get(h)
            if not p:
                continue
            mf = p['metafields']
            if mf.get('bedrukbaar') and not (mf.get('drukopties') or {}).get('optie'):
                mf['bedrukbaar'] = False
                mf['drukopties'] = None
                p['tags'] = [t for t in p['tags'] if t != 'bedrukbaar']
                self.fix(h, 'bedrukbaar → false, drukopties → null, tag bedrukbaar removed', why)
        # 3. CONTRACT: drukopties.aanlevering / levertijd unified (G5 note); body text kept consistent
        for p in products:
            d = p['metafields'].get('drukopties')
            if not d:
                continue
            if d.get('aanlevering') and 'dpi' in d['aanlevering']:
                old = d['aanlevering']
                d['aanlevering'] = UNIFIED_AANLEVERING
                self.fix(p['handle'], f'drukopties.aanlevering {old!r} → {UNIFIED_AANLEVERING!r}',
                         'G5: one aanlever rule on every bedrukbaar product (matches the theme help text)')
                if 'PNG van minimaal 300 dpi' in p['body_html']:
                    p['body_html'] = p['body_html'].replace('PNG van minimaal 300 dpi', 'PNG van minimaal 2000 px breed')
                    self.fix(p['handle'], "body_html 'PNG van minimaal 300 dpi' → 'PNG van minimaal 2000 px breed'",
                             'keep the copy in line with drukopties.aanlevering')
            if d.get('levertijd') and d['levertijd'] != '10–15 werkdagen na akkoord drukproef':
                old = d['levertijd']
                d['levertijd'] = '10–15 werkdagen na akkoord drukproef'
                self.fix(p['handle'], f'drukopties.levertijd {old!r} → unified', 'G5: one print lead time everywhere')
        # 4. configurator variants are made to order (CONTRACT)
        for p in products:
            if p['metafields'].get('configurator'):
                changed = [v['sku'] for v in p['variants'] if v.get('inventory_policy') != 'continue']
                for v in p['variants']:
                    v['inventory_policy'] = 'continue'
                if changed:
                    self.fix(p['handle'], f'inventory_policy → continue on {len(changed)} variant(s)',
                             'CONTRACT: configurator variants are made to order (G3 note)')
        # 5. past_op corrections
        for h, (drop, why) in PAST_OP_REMOVE.items():
            p = P.get(h)
            if not p:
                continue
            cur = p['metafields'].get('past_op') or []
            gone = [x for x in cur if x in drop]
            if gone:
                p['metafields']['past_op'] = [x for x in cur if x not in drop]
                self.fix(h, f'past_op: removed {", ".join(gone)}', why)
        # 6. maatgids (size guide pages exist in parts/content.json)
        page_handles = {pg['handle'] for pg in self.content.get('pages', [])}
        for page, handles in MAATGIDS.items():
            if page not in page_handles:
                self.warnings.append(f'maatgids page {page} missing; not linked')
                continue
            for h in handles:
                p = P.get(h)
                if p and not p['metafields'].get('maatgids'):
                    p['metafields']['maatgids'] = page
                    self.fix(h, f'maatgids → page {page}', 'suggested in the G1/G4/G5 data notes')
        # 6b. downloads: every PDF that exists for the product (node catalog/tools/productblad.mjs renders the productbladen of the tents)
        for p in products:
            files = [f'{k}-{p["handle"]}.pdf' for k in DOWNLOAD_KINDS if (IMAGES / f'{k}-{p["handle"]}.pdf').exists()]
            if files and not p['metafields'].get('downloads'):
                p['metafields']['downloads'] = files
        # 7. custom.gewicht_kg rounded to 0 in the skeleton (light items): take the first variant's weight. Only a 0, never an
        #    empty value: the skeleton leaves it empty on products whose sizes weigh 22 to 90 kg (printed easy-ups), so the spec
        #    shows the chosen variant's weight instead of the smallest size on every size (merchandising review 3)
        for p in products:
            mf = p['metafields']
            if 'gewicht_kg' in mf and mf['gewicht_kg'] is not None and not mf['gewicht_kg'] and p['variants'] and p['variants'][0].get('grams'):
                mf['gewicht_kg'] = round(p['variants'][0]['grams'] / 1000, 3)
                self.fix(p['handle'], f'gewicht_kg 0 → {mf["gewicht_kg"]}', 'skeleton rounded a light item to 0 kg')
        # 8. CONTRACT tag `pallet` (large shipments) must agree with custom.verzending = pallet
        for p in products:
            if p['metafields'].get('verzending') == 'pallet' and 'pallet' not in p['tags']:
                p['tags'] = p['tags'] + ['pallet']
                self.fix(p['handle'], 'tag pallet added', 'custom.verzending is pallet (tag and metafield must agree)')
            elif 'pallet' in p['tags'] and p['metafields'].get('verzending') != 'pallet':
                self.warnings.append(f"{p['handle']}: tag pallet but verzending {p['metafields'].get('verzending')!r}")
        # 9. gift cards are not taxed at sale (VAT is due on redemption; Shopify does not tax gift cards)
        for p in products:
            if p.get('gift_card'):
                for v in p['variants']:
                    if v.get('taxable'):
                        v['taxable'] = False
                self.fix(p['handle'], 'variants taxable → false', 'gift card (multi-purpose voucher)')

    def find_variant(self, prod, want: dict):
        names = [o['name'] for o in prod['options']]
        hits = []
        for v in prod['variants']:
            vals = [v.get(f'option{i + 1}') for i in range(len(names))]
            if all(n in names and vals[names.index(n)] == val for n, val in want.items()):
                hits.append(v)
        return hits

    def resolve_bundles(self, products):
        P = self.by_handle
        self.bundle_errors = []
        for p in products:
            b = p.get('bundle')
            if not b:
                continue
            for cpv in b.get('componenten_per_variant', []):
                vals = cpv['variant']
                bv = [v for v in p['variants']
                      if [v.get(f'option{i + 1}') for i in range(len(vals))] == vals]
                if len(bv) != 1:
                    self.bundle_errors.append(f'{p["handle"]}: bundle variant {vals} matches {len(bv)} variants')
                    continue
                bv = bv[0]
                skus, qtys, los = [], [], 0
                for c in cpv['componenten']:
                    cp = P.get(c['handle'])
                    if not cp:
                        self.bundle_errors.append(f'{p["handle"]} {vals}: component product {c["handle"]} missing')
                        continue
                    hits = self.find_variant(cp, c.get('variant') or {})
                    if len(hits) != 1:
                        self.bundle_errors.append(
                            f'{p["handle"]} {vals}: component {c["handle"]} {c.get("variant")} matches {len(hits)} variants')
                        continue
                    skus.append(hits[0]['sku'])
                    qtys.append(int(c.get('aantal', 1)))
                    los += hits[0]['price'] * int(c.get('aantal', 1))
                bv['metafields']['componenten'] = skus
                bv['metafields']['component_aantallen'] = qtys
                bv['bundle_los_totaal'] = los
                if cpv.get('los_totaal') is not None and round(cpv['los_totaal'] * 100) != los:
                    self.bundle_errors.append(
                        f'{p["handle"]} {vals}: los_totaal {cpv["los_totaal"]} ≠ component prices {los / 100:.2f}')
                if cpv.get('pakketprijs') is not None and round(cpv['pakketprijs'] * 100) != bv['price']:
                    self.bundle_errors.append(
                        f'{p["handle"]} {vals}: pakketprijs {cpv["pakketprijs"]} ≠ variant price {bv["price"] / 100:.2f}')

