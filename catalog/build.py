def render_spec(img, size=2000):
    r = copy.deepcopy(img['render'])
    r.pop('shared_with', None)  # bookkeeping in the skeleton, not a render parameter
    spec = {'model': r.get('model')}
    if r.get('params') is not None:
        spec['params'] = r['params']
    # several products in one image: render.mjs reads a top-level "items" list (renders/js/main.js), not model 'items'
    if spec['model'] in (None, 'items') and isinstance(spec.get('params'), dict) and spec['params'].get('items'):
        spec = {'model': 'items', 'items': spec['params']['items'], **{k: v for k, v in spec['params'].items() if k != 'items'}}
    for k, v in r.items():
        if k not in ('model', 'params'):
            spec[k] = v
    spec.setdefault('angle', 'hero')
    if 'imageWidth' not in spec and 'size' not in spec:
        spec['size'] = size
    return spec


def models_in(spec) -> list[str]:
    if not spec:
        return []
    if spec.get('items'):
        return [it.get('model') for it in spec['items']]
    return [spec.get('model')]


def image_jobs(products, article_jobs, existing_models=(), collections=()):
    jobs = {}
    for p in products:
        for img in p['images']:
            f = img['file']
            j = jobs.get(f)
            if not j:
                j = jobs[f] = {
                    'file': f, 'out': f'catalog/images/{f}', 'kind': 'product',
                    'priority': img.get('priority', 3), 'role': img.get('role'), 'kleur': img.get('kleur'),
                    'model': img['render'].get('model'), 'model_status': img.get('model_status'),
                    'spec': render_spec(img), 'alt': img['alt'], 'alt_hint': img.get('alt_hint'),
                    'used_by': [],
                    'exists': is_real(f),          # a real render is in catalog/images
                    'draft': is_draft(f),          # only the placeholder card is there
                }
            else:
                if json.dumps(render_spec(img), sort_keys=True) != json.dumps(j['spec'], sort_keys=True):
                    j.setdefault('spec_conflicts', []).append(p['handle'])
                j['priority'] = min(j['priority'], img.get('priority', 3))
            j['used_by'].append({'handle': p['handle'], 'role': img.get('role'),
                                 'variant': any(v.get('image') == f for v in p['variants'])})
    for a in article_jobs:
        f = a['file']
        if a['kind'] == 'brand-copy':
            jobs.setdefault(f, {
                'file': f, 'out': f'catalog/images/{f}', 'kind': 'brand-copy', 'priority': 1, 'role': 'banner',
                'kleur': None, 'model': None, 'model_status': 'copied', 'spec': None, 'from': a['from'],
                'alt': a.get('alt'), 'used_by': [{'article': a['article'], 'role': 'banner'}],
                'exists': (IMAGES / f).exists(),
            })
            continue
        spec = a['spec']
        model = spec.get('model') or ('items' if spec.get('items') else None)
        if 'items' in spec and 'model' not in spec:
            spec = {'model': 'items', **spec}
        status = 'existing' if all(m in existing_models for m in models_in(spec)) else 'needs-model'
        jobs.setdefault(f, {
            'file': f, 'out': f'catalog/images/{f}', 'kind': 'article-banner', 'priority': 2, 'role': 'banner',
            'kleur': None, 'model': model, 'model_status': status, 'spec': spec, 'alt': a.get('alt'),
            'used_by': [{'article': a['article'], 'role': 'banner'}], 'exists': (IMAGES / f).exists(),
        })
    for c in collections or ():
        cr = c.get('image_render')
        if not cr:
            continue
        f = cr['file']
        spec = render_spec({'render': cr['render']})
        jobs.setdefault(f, {
            'file': f, 'out': f'catalog/images/{f}', 'kind': 'collection', 'priority': 2, 'role': 'collection',
            'kleur': None, 'model': spec.get('model'),
            'model_status': 'existing' if all(m in existing_models for m in models_in(spec)) else 'needs-model',
            'spec': spec, 'alt': cr.get('alt'), 'used_by': [{'collection': c['handle'], 'role': 'image'}],
            'exists': is_real(f), 'draft': is_draft(f),
        })
    lst = sorted(jobs.values(), key=lambda j: (j['priority'], j['kind'] != 'product', j['file']))
    return lst


def demo_stock(p, v) -> int:
    """PREVIEW ONLY (standing item a): plausible demo stock so the renderer shows every stock state. Deterministic per SKU: ~7% on
    backorder (0, policy continue: 'Leverbaar over 2–3 weken'), ~8% low (1-3: 'Nog x op voorraad'), the rest in stock with a quantity that
    fits the price. products.csv keeps 0 + continue: the owner enters the real counts (catalog/stock.csv or Shopify)."""
    h = zlib.crc32(v['sku'].encode())
    bucket = h % 100
    if bucket < 7:
        return 0
    if bucket < 15:
        return 1 + h % 3
    price = v['price'] / 100
    # catalog round 4: in stock means more than the low-stock line (1-3); the dearest goods were 1-4 and read 'Nog 2 op voorraad' on a quarter
    # of all variants
    lo, hi = (40, 240) if price < 15 else (12, 90) if price < 60 else (6, 30) if price < 250 else (4, 14) if price < 1000 else (4, 9)
    return lo + (h // 100) % (hi - lo + 1)


