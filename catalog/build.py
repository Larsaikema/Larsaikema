class Build:
    def __init__(self):
        self.fixes: list[dict] = []
        self.warnings: list[str] = []
        self.skeleton = read_json(HERE / 'skeleton.json')
        self.content = read_json(PARTS / 'content.json')
        self.parts: dict[str, dict] = {}
        self.part_group: dict[str, str] = {}
        self.coll_parts: dict[str, dict] = {}
        self.page_parts: dict[str, dict] = {}
        self.part_notes: list[dict] = []
        for f in sorted(glob.glob(str(PARTS / 'g*.json'))):
            d = read_json(Path(f))
            meta = d.get('_meta', {})
            group = meta.get('group') or Path(f).stem.split('-')[0].upper()
            for note in meta.get('data_notes', []) or []:
                self.part_notes.append({'group': group, 'note': note})
            for note in meta.get('issues_for_skeleton', []) or []:
                self.part_notes.append({'group': group, 'note': note})
            for key, val in d.items():
                if key == '_meta':
                    continue
                if key == '_collections':
                    for h, c in val.items():
                        self.coll_parts[h] = c
                    continue
                if key == '_pages':
                    for h, pg in val.items():
                        self.page_parts[h] = pg
                    continue
                if key in self.parts:
                    raise SystemExit(f'duplicate product copy for {key} in {f}')
                self.parts[key] = val
                self.part_group[key] = group
        self.swatches = swatch_table()

    def fix(self, handle, what, why):
        self.fixes.append({'handle': handle, 'change': what, 'why': why})

    # ---------------------------------------------------------------- products
    def products(self):
        out = []
        for sp in self.skeleton['products']:
            h = sp['handle']
            part = self.parts.get(h)
            if part is None:
                raise SystemExit(f'no copy part for product {h}')
            out.append(self.merge_product(sp, part))
        self.by_handle = {p['handle']: p for p in out}
        self.apply_fixes(out)
        self.resolve_bundles(out)
        self.export_images(out)
        return out

    def export_images(self, products):
        """Which images go to Shopify: only real renders. A variant whose own render is still a draft (or missing) shows the
        product's real hero instead; a product without any real render exports no image at all (never a placeholder card)."""
        self.image_stats = {'real': 0, 'draft': 0, 'missing': 0, 'products_without_image': [], 'variants_on_hero': 0}
        for p in products:
            for img in p['images']:
                f = img['file']
                img['draft'] = is_draft(f)
                img['exported'] = (IMAGES / f).exists() and not img['draft']
                self.image_stats['real' if img['exported'] else ('draft' if img['draft'] else 'missing')] += 1
            real = [i['file'] for i in p['images'] if i['exported']]
            if not real:
                self.image_stats['products_without_image'].append(p['handle'])
            for v in p['variants']:
                own = v.get('image')
                if own and own in real:
                    v['export_image'] = own
                else:
                    v['export_image'] = real[0] if real else None
                    if own and real:
                        self.image_stats['variants_on_hero'] += 1

    def merge_product(self, sp, part):
        p = copy.deepcopy(sp)
        mf = p['metafields']
        p['body_html'] = part.get('body_html') or ''
        seo = part.get('seo') or {}
        p['seo'] = {'title': seo.get('title'), 'description': seo.get('description')}
        for k in ('kenmerk_kort', 'usps', 'specificaties', 'faq', 'included', 'excluded', 'drukopties',
                  'configurator', 'maatwerk'):
            if k in part and part[k] is not None:
                mf[k] = part[k]
        for k in list(mf):
            if k not in PRODUCT_MF_TYPES:
                raise SystemExit(f'{p["handle"]}: metafield {k} is not in the contract')
        alts = part.get('image_alts') or {}
        for img in p['images']:
            alt = (alts.get(img['file']) or '').strip()
            if not alt:
                hint = img.get('alt_hint')
                alt = f"{p['title']}{', ' + hint if hint else ''}"
                self.warnings.append(f"{p['handle']}: no alt text for {img['file']} in the copy part, used fallback")
            img['alt'] = alt
        # what the copy says the owner/supplier must confirm (not for the storefront)
        claims = list(part.get('claims') or [])
        claims += [c for c in html_claims(p['body_html']) if c not in claims]
        p['claims'] = claims
        p['copy_group'] = self.part_group.get(p['handle'], p.get('copy_group'))
        # remove skeleton-only working fields from the merged record
        for k in ('copy_brief', 'seo_keywords', 'price_range_eur'):
            p.pop(k, None)
        # variants: native per-variant metafields container
        for v in p['variants']:
            v.setdefault('metafields', {})
        return p

    def apply_fixes(self, products):
        P = self.by_handle
        # 1. CONTRACT: no print lead time in custom.levertijd (drukopties.levertijd carries it)
        for p in products:
            mf = p['metafields']
            lev = mf.get('levertijd')
            if lev and 'drukproef' in lev:
                new = re.sub(r'\s*\((?:bij\s+)?bedrukt:[^)]*\)', '', lev).strip()
                if 'drukproef' in new or not mf.get('bedrukbaar'):
                    new = None
                mf['levertijd'] = new
                self.fix(p['handle'], f'custom.levertijd {lev!r} → {new!r}',
                         'CONTRACT: print lead time lives in drukopties.levertijd, not in levertijd (G5 note)')
        # 2. bedrukbaar without a print variant
        for h, why in NOT_PRINTABLE.items():
            p = P.get(h)
            if not p:
                continue
            mf = p['metafields']
            if mf.get('bedrukbaar') and not (mf.get('drukopties') or {}).get('optie'):
                mf['bedrukbaar'] = False
                mf['drukopties'] = None
                p['tags'] = [t for t in p['tags'] if t != 'bedrukbaar']
                self.fix(h, 'bedrukbaar → false, drukopties → null, tag bedrukbaar removed', why)
        # 3. CONTRACT: drukopties.aanlevering / levertijd unified (G5 note); body text kept consistent
        for p in products:
            d = p['metafields'].get('drukopties')
            if not d:
                continue
            if d.get('aanlevering') and 'dpi' in d['aanlevering']:
                old = d['aanlevering']
                d['aanlevering'] = UNIFIED_AANLEVERING
                self.fix(p['handle'], f'drukopties.aanlevering {old!r} → {UNIFIED_AANLEVERING!r}',
                         'G5: one aanlever rule on every bedrukbaar product (matches the theme help text)')
                if 'PNG van minimaal 300 dpi' in p['body_html']:
                    p['body_html'] = p['body_html'].replace('PNG van minimaal 300 dpi', 'PNG van minimaal 2000 px breed')
                    self.fix(p['handle'], "body_html 'PNG van minimaal 300 dpi' → 'PNG van minimaal 2000 px breed'",
                             'keep the copy in line with drukopties.aanlevering')
            if d.get('levertijd') and d['levertijd'] != '10–15 werkdagen na akkoord drukproef':
                old = d['levertijd']
                d['levertijd'] = '10–15 werkdagen na akkoord drukproef'
                self.fix(p['handle'], f'drukopties.levertijd {old!r} → unified', 'G5: one print lead time everywhere')
        # 4. configurator variants are made to order (CONTRACT)
        for p in products:
            if p['metafields'].get('configurator'):
                changed = [v['sku'] for v in p['variants'] if v.get('inventory_policy') != 'continue']
                for v in p['variants']:
                    v['inventory_policy'] = 'continue'
                if changed:
                    self.fix(p['handle'], f'inventory_policy → continue on {len(changed)} variant(s)',
                             'CONTRACT: configurator variants are made to order (G3 note)')
        # 5. past_op corrections
        for h, (drop, why) in PAST_OP_REMOVE.items():
            p = P.get(h)
            if not p:
                continue
            cur = p['metafields'].get('past_op') or []
            gone = [x for x in cur if x in drop]
            if gone:
                p['metafields']['past_op'] = [x for x in cur if x not in drop]
                self.fix(h, f'past_op: removed {", ".join(gone)}', why)
        # 6. maatgids (size guide pages exist in parts/content.json)
        page_handles = {pg['handle'] for pg in self.content.get('pages', [])}
        for page, handles in MAATGIDS.items():
            if page not in page_handles:
                self.warnings.append(f'maatgids page {page} missing; not linked')
                continue
            for h in handles:
                p = P.get(h)
                if p and not p['metafields'].get('maatgids'):
                    p['metafields']['maatgids'] = page
                    self.fix(h, f'maatgids → page {page}', 'suggested in the G1/G4/G5 data notes')
        # 6b. downloads: every PDF that exists for the product (node catalog/tools/productblad.mjs renders the productbladen of the tents)
        for p in products:
            files = [f'{k}-{p["handle"]}.pdf' for k in DOWNLOAD_KINDS if (IMAGES / f'{k}-{p["handle"]}.pdf').exists()]
            if files and not p['metafields'].get('downloads'):
                p['metafields']['downloads'] = files
        # 7. custom.gewicht_kg rounded to 0 in the skeleton (light items): take the first variant's weight
        for p in products:
            mf = p['metafields']
            if 'gewicht_kg' in mf and not mf['gewicht_kg'] and p['variants'] and p['variants'][0].get('grams'):
                mf['gewicht_kg'] = round(p['variants'][0]['grams'] / 1000, 3)
                self.fix(p['handle'], f'gewicht_kg 0 → {mf["gewicht_kg"]}', 'skeleton rounded a light item to 0 kg')
        # 8. CONTRACT tag `pallet` (large shipments) must agree with custom.verzending = pallet
        for p in products:
            if p['metafields'].get('verzending') == 'pallet' and 'pallet' not in p['tags']:
                p['tags'] = p['tags'] + ['pallet']
                self.fix(p['handle'], 'tag pallet added', 'custom.verzending is pallet (tag and metafield must agree)')
            elif 'pallet' in p['tags'] and p['metafields'].get('verzending') != 'pallet':
                self.warnings.append(f"{p['handle']}: tag pallet but verzending {p['metafields'].get('verzending')!r}")
        # 9. gift cards are not taxed at sale (VAT is due on redemption; Shopify does not tax gift cards)
        for p in products:
            if p.get('gift_card'):
                for v in p['variants']:
                    if v.get('taxable'):
                        v['taxable'] = False
                self.fix(p['handle'], 'variants taxable → false', 'gift card (multi-purpose voucher)')

    def find_variant(self, prod, want: dict):
        names = [o['name'] for o in prod['options']]
        hits = []
        for v in prod['variants']:
            vals = [v.get(f'option{i + 1}') for i in range(len(names))]
            if all(n in names and vals[names.index(n)] == val for n, val in want.items()):
                hits.append(v)
        return hits

    def resolve_bundles(self, products):
        P = self.by_handle
        self.bundle_errors = []
        for p in products:
            b = p.get('bundle')
            if not b:
                continue
            for cpv in b.get('componenten_per_variant', []):
                vals = cpv['variant']
                bv = [v for v in p['variants']
                      if [v.get(f'option{i + 1}') for i in range(len(vals))] == vals]
                if len(bv) != 1:
                    self.bundle_errors.append(f'{p["handle"]}: bundle variant {vals} matches {len(bv)} variants')
                    continue
                bv = bv[0]
                skus, qtys, los = [], [], 0
                for c in cpv['componenten']:
                    cp = P.get(c['handle'])
                    if not cp:
                        self.bundle_errors.append(f'{p["handle"]} {vals}: component product {c["handle"]} missing')
                        continue
                    hits = self.find_variant(cp, c.get('variant') or {})
                    if len(hits) != 1:
                        self.bundle_errors.append(
                            f'{p["handle"]} {vals}: component {c["handle"]} {c.get("variant")} matches {len(hits)} variants')
                        continue
                    skus.append(hits[0]['sku'])
                    qtys.append(int(c.get('aantal', 1)))
                    los += hits[0]['price'] * int(c.get('aantal', 1))
                bv['metafields']['componenten'] = skus
                bv['metafields']['component_aantallen'] = qtys
                bv['bundle_los_totaal'] = los
                if cpv.get('los_totaal') is not None and round(cpv['los_totaal'] * 100) != los:
                    self.bundle_errors.append(
                        f'{p["handle"]} {vals}: los_totaal {cpv["los_totaal"]} ≠ component prices {los / 100:.2f}')
                if cpv.get('pakketprijs') is not None and round(cpv['pakketprijs'] * 100) != bv['price']:
                    self.bundle_errors.append(
                        f'{p["handle"]} {vals}: pakketprijs {cpv["pakketprijs"]} ≠ variant price {bv["price"] / 100:.2f}')

