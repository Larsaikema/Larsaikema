CLAIM_COMMENT = re.compile(r'<!--\s*claim:(.*?)-->', re.S)

# Draft placeholders ("VOORBEELD · render volgt" cards from catalog/tools/draft_images.py) are listed in catalog/images/.drafts.json
# with the sha256 of the card. A file is a draft only while its bytes still match that hash, so a real render that overwrites
# the card is picked up automatically. Drafts are never exported: not as Image Src, not as Variant Image, not in the fixture.
DRAFTS_FILE = IMAGES / '.drafts.json'
_DRAFTS: dict | None = None


def file_sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, 'rb') as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def draft_registry() -> dict:
    global _DRAFTS
    if _DRAFTS is None:
        try:
            d = read_json(DRAFTS_FILE)
        except (OSError, ValueError):
            d = {}
        _DRAFTS = d.get('files', {}) if isinstance(d, dict) else {f: None for f in d}  # legacy: a bare list (no hashes)
    return _DRAFTS


def is_draft(file: str) -> bool:
    reg = draft_registry()
    if file not in reg:
        return False
    path = IMAGES / file
    if not path.exists():
        return False
    if reg[file] is None:  # legacy list entry: still the 1200 px card?
        try:
            with open(path, 'rb') as fh:
                head = fh.read(64)
            return b'VP8' in head and _webp_size(path) == (1200, 1200)
        except OSError:
            return True
    return file_sha256(path) == reg[file]


def _webp_size(path: Path):
    data = path.read_bytes()[:40]
    if data[12:16] == b'VP8X':
        return (1 + int.from_bytes(data[24:27], 'little'), 1 + int.from_bytes(data[27:30], 'little'))
    if data[12:16] == b'VP8 ':
        return (int.from_bytes(data[26:28], 'little') & 0x3FFF, int.from_bytes(data[28:30], 'little') & 0x3FFF)
    if data[12:16] == b'VP8L':
        b = data[21:25]
        return (1 + (((b[1] & 0x3F) << 8) | b[0]), 1 + (((b[3] & 0xF) << 10) | (b[2] << 2) | ((b[1] & 0xC0) >> 6)))
    return None


def is_real(file: str) -> bool:
    """The file exists in catalog/images and is a real render (not a draft placeholder)."""
    return bool(file) and (IMAGES / file).exists() and not is_draft(file)


def strip_comments(html: str | None) -> str:
    """Storefront HTML: drop <!-- claim: … --> and any other HTML comment (internal notes)."""
    if not html:
        return ''
    out = re.sub(r'[ \t]*<!--.*?-->', '', html, flags=re.S)  # the marker and the space in front of it
    return out.strip()


def strip_deep(obj):
    """strip_comments on every string that contains an HTML comment, recursively (template block data)."""
    if isinstance(obj, str):
        return strip_comments(obj) if '<!--' in obj else obj
    if isinstance(obj, list):
        return [strip_deep(x) for x in obj]
    if isinstance(obj, dict):
        return {k: strip_deep(v) for k, v in obj.items()}
    return obj


def html_claims(html: str | None) -> list[str]:
    return [re.sub(r'\s+', ' ', m).strip() for m in CLAIM_COMMENT.findall(html or '')]


def stable_id(seed: str, base: int) -> int:
    """Same as tools/preview/lib/util.rb Util.stable_id (crc32 of the UTF-8 seed)."""
    return base + (zlib.crc32(seed.encode('utf-8')) % 900_000_000_000)


def variant_id(handle: str, opts: list) -> int:
    vals = [str(o) for o in opts if o is not None]
    return stable_id(f"variant:{handle}:{'/'.join(vals)}", 40_000_000_000_000)


def money(cents: int | None) -> str:
    return '' if cents is None else f'{cents / 100:.2f}'


def decimal_str(x) -> str:
    f = float(x)
    s = repr(f)
    return s if '.' in s or 'e' in s else s + '.0'


def mf_value_string(mtype: str, value) -> str:
    """Admin-API value string for a native value."""
    if mtype.startswith('list.'):
        inner = mtype[5:]
        if inner == 'number_integer':
            return json.dumps([int(v) for v in value])
        return json.dumps(list(value), ensure_ascii=False)
    if mtype in ('json', 'rich_text_field'):
        return json.dumps(value, ensure_ascii=False)
    if mtype == 'boolean':
        return 'true' if value else 'false'
    if mtype == 'number_decimal':
        return decimal_str(value)
    if mtype == 'number_integer':
        return str(int(value))
    return str(value)


def empty(v) -> bool:
    return v is None or v == '' or v == [] or v == {}


def read_json(path: Path):
    with open(path, encoding='utf-8') as fh:
        return json.load(fh)


def write_json(path: Path, data, compact: bool = False):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + '.tmp')
    with open(tmp, 'w', encoding='utf-8') as fh:
        if compact:
            json.dump(data, fh, ensure_ascii=False, separators=(',', ':'))
        else:
            json.dump(data, fh, ensure_ascii=False, indent=1)
        fh.write('\n')
    tmp.replace(path)


def swatch_table() -> dict:
    """Kleur → hex from the theme setting swatch_colors (CONTRACT: every catalog colour is listed there)."""
    table = {}
    try:
        schema = read_json(THEME_SCHEMA)
        for group in schema:
            for st in group.get('settings', []) or []:
                if st.get('id') == 'swatch_colors':
                    for line in (st.get('default') or '').splitlines():
                        if ':' in line:
                            name, hexv = line.split(':', 1)
                            table[name.strip()] = hexv.strip()
    except (OSError, ValueError):
        pass
    # brand.md v3 colour the theme default may still lack (skeleton.theme_requirements)
    table.setdefault('Warm wit', '#F4E3BC')
    return table


