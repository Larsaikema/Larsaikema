"""Embed the one-colour brand print artwork (brand/svg/print-*.svg) as path data in
renders/js/brandPrints.js, so model builders (which run synchronously in the page and
cannot read files outside renders/) can resolve print specs like
  {"svg": "brand/tools/print-wordmark-klein.json"}  or  {"svg": "print-wordmark-klein"}
Re-run after a brand change:  python3 renders/tools/make_brand_prints.py
"""
import json, os, re
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
SVG = os.path.join(REPO, 'brand', 'svg')
out = {}
for name in sorted(os.listdir(SVG)):
    if not (name.startswith('print-') and name.endswith('.svg')):
        continue
    s = open(os.path.join(SVG, name)).read()
    vb = [float(v) for v in re.search(r'viewBox="([^"]+)"', s).group(1).split()[2:]]
    d = ''.join(re.search(r' d="([^"]+)"', m.group(1)).group(1) for m in re.finditer(r'<path([^>]*)/>', s))
    out[name[:-4]] = {'d': d, 'vb': vb}
js = ('// GENERATED by renders/tools/make_brand_prints.py from brand/svg/print-*.svg — do not edit by hand.\n'
      '// One-colour print artwork (SVG path data + viewBox) for printed products (belts, covers, walls).\n'
      'export const BRAND_PRINTS = ' + json.dumps(out, indent=1) + ';\n\n'
      '// Resolve a print spec to {d, vb}: accepts {d, vb} as is, or {svg: "<any path or name>"} whose\n'
      '// basename (without extension) names an embedded artwork, e.g. "brand/tools/print-wordmark-klein.json".\n'
      'export function resolvePrint(spec) {\n'
      '  if (!spec) return null;\n'
      '  if (typeof spec === "string") spec = { svg: spec };\n'
      '  if (spec.d && spec.vb) return spec;\n'
      '  const key = String(spec.svg || spec.name || "").split("/").pop().replace(/\\.(json|svg)$/i, "");\n'
      '  const art = BRAND_PRINTS[key] || null;\n'
      '  return art ? { ...spec, d: art.d, vb: art.vb } : null;\n'
      '}\n')
open(os.path.join(REPO, 'renders', 'js', 'brandPrints.js'), 'w').write(js)
print('wrote', len(out), 'artworks:', ', '.join(out))
